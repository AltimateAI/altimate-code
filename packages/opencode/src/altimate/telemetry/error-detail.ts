/**
 * Fixed-vocabulary template of an error's first line. Words are split on any non-letter
 * character and lowercased; a word survives only if it is in ERROR_VOCABULARY, every other
 * run becomes `<x>`. The output holds only vocabulary words, `<x>` and spaces, so user
 * text, identifiers, paths, values and SQL cannot appear.
 */
export function templateErrorMessage(raw: string): string {
  const first = raw.split(/[\r\n\u2028\u2029]/, 1)[0]
  const out: string[] = []
  for (const token of first.split(/[^A-Za-z]+/)) {
    if (!token) continue
    const word = token.toLowerCase()
    const piece = ERROR_VOCABULARY.has(word) ? word : PLACEHOLDER
    if (piece === PLACEHOLDER && out[out.length - 1] === PLACEHOLDER) continue
    out.push(piece)
  }
  // non-letter characters that carried a value (digits, symbols) leave a gap that must stay visible
  return out.join(" ").slice(0, MAX_MESSAGE)
}

/** Hash input is unchanged from before the detail fields existed, so fingerprints stay stable. */
export function describeToolError(raw: string) {
  return {
    errorHash: Telemetry.hashError(Telemetry.maskString(raw).slice(0, 500)),
    errorMessage: templateErrorMessage(raw),
  }
}

// Exact messages of PermissionNext/PermissionV1 RejectedError and CorrectedError and of
// Question.RejectedError, optionally behind the "Name: " prefix that toString() adds.
const USER_REJECTION =
  /^(?:\w+: )?(?:The user rejected permission to use this specific tool call(?:\.$| with the following feedback: )|The user dismissed this question$)/

/**
 * True when a tool "error" is the user declining a permission prompt or dismissing a
 * question. That is a user decision, not a tool failure, so it is kept out of tool error
 * telemetry. Config-rule denials and every other permission failure still count.
 */
export function isUserRejection(raw: string): boolean {
  return USER_REJECTION.test(raw)
}

export function buildErrorFingerprintEvent(
  sessionID: string,
  err: {
    errorHash: string
    errorClass: string
    toolName: string
    toolCategory: string
    errorMessage: string
    recovered: boolean
    recoveryTool: string
  },
): Telemetry.Event {
  return {
    type: "error_fingerprint",
    timestamp: Date.now(),
    session_id: sessionID,
    error_hash: err.errorHash,
    error_class: err.errorClass,
    tool_name: err.toolName,
    tool_category: err.toolCategory,
    error_message: err.errorMessage,
    recovery_successful: err.recovered,
    recovery_tool: err.recoveryTool,
  }
}

