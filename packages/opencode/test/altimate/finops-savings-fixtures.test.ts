// altimate_change - new file
/**
 * The savings formatters over reports a real altimate-core binding produced (see fixtures/finops-savings/
 * generate.ts), so a field core renames or drops shows up here as text, not as a guess about its shape.
 */
import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { initTool } from "./tool-fixture"
import * as Dispatcher from "../../src/altimate/native/dispatcher"
import * as Registry from "../../src/altimate/native/connections/registry"
import * as Databricks from "../../src/altimate/tools/finops-databricks-savings"
import * as Snowflake from "../../src/altimate/tools/finops-snowflake-savings"
import type {
  DatabricksSavingsEvidence,
  DatabricksSavingsReport,
  DatabricksSavingsResult,
  SnowflakeSavingsEvidence,
  SnowflakeSavingsReport,
  SnowflakeSavingsResult,
} from "../../src/altimate/native/types"
import databricksFull from "./fixtures/finops-savings/databricks-report.json"
import databricksUnpriced from "./fixtures/finops-savings/databricks-unpriced-report.json"
import snowflakeFull from "./fixtures/finops-savings/snowflake-report.json"
import snowflakeUnpriced from "./fixtures/finops-savings/snowflake-unpriced-report.json"

type Fields<E extends { kind: string }> = { [K in E["kind"]]: (keyof Extract<E, { kind: K }>)[] }

// Every field of each evidence kind, as core's `Evidence` enum declares it. Checked against the generated
// reports below, so regenerating them from a core that changed a kind fails here.
const DATABRICKS_FIELDS: Fields<DatabricksSavingsEvidence> = {
  serverless: ["kind", "warehouse_type", "warehouse_size", "idle_ratio", "wall_clock_uptime_hours", "total_query_count", "price_per_dbu", "serverless_price_per_dbu", "current_dbu_cost", "projected_serverless_dbu_cost", "wasted_cost"],
  over_sized: ["kind", "current_size", "recommended_size", "available_cores", "p99_utilization", "parallelism_query_count", "no_spill_query_pct", "no_queue_query_pct", "current_dbu_per_hour", "recommended_dbu_per_hour", "total_cost", "wasted_cost"],
  idle_cluster: ["kind", "idle_pattern", "idle_ratio", "auto_termination_minutes", "active_days", "avg_cpu_active_pct", "peak_cpu_active_pct", "total_cost", "wasted_cost"],
  job_on_all_purpose: ["kind", "host_cluster_id", "host_cluster_name", "trigger_type", "task_runs", "task_hours", "estimated_dbus", "all_purpose_rate_per_dbu", "jobs_rate_per_dbu", "jobs_rate_estimated", "wasted_cost"],
}
const SNOWFLAKE_FIELDS: Fields<SnowflakeSavingsEvidence> = {
  high_idle_time: ["kind", "idle_ratio", "idle_seconds", "active_seconds", "flagged_days", "credits_used", "price_per_credit", "wasted_cost"],
  downsize_warehouse: ["kind", "current_size", "recommended_size", "short_period_percent", "sub_five_second_percent", "query_count", "cost_basis", "price_per_credit"],
  underutilized_cluster: ["kind", "max_cluster_count", "recommended_max_cluster_count", "highest_idle_percent", "flagged_days"],
  frequent_restart: ["kind", "bounces", "double_billed_seconds", "credits_per_hour", "flagged_days", "price_per_credit"],
}

const WINDOW = { start: "2026-01-05", end: "2026-01-12" }

const databricksResult = (report: unknown): DatabricksSavingsResult => {
  const typed = report as DatabricksSavingsReport
  return {
    success: true,
    window: WINDOW,
    warehouse: "synthetic_dbx",
    ran_on: "synthetic-warehouse",
    workspaces_checked: 2,
    warehouses_checked: 3,
    clusters_checked: 2,
    jobs_checked: 2,
    skipped: [],
    limited: [],
    warehouses: [],
    report: typed,
  }
}

const snowflakeResult = (report: unknown, source: "rate_sheet" | "list_price"): SnowflakeSavingsResult => {
  const typed = report as SnowflakeSavingsReport
  return {
    success: true,
    window: WINDOW,
    warehouse: "synthetic_sf",
    ran_on: "SYNTHETIC_IDLE_WH",
    warehouses_checked: typed.findings.length,
    price: { per_credit: typed.price_per_credit, source, as_of: "2026-01-11" },
    skipped: [],
    limited: [],
    warehouses: [],
    report: typed,
  }
}

/** Text a field that is missing, or a number that is not one, would leave behind. */
function expectNoHoles(text: string) {
  expect(text).not.toMatch(/undefined|NaN|null|\[object Object\]/)
}

describe("savings fixtures generated by altimate-core", () => {
  beforeEach(() => {
    Dispatcher.reset()
    // The tools resolve a connection before running; the check itself is stubbed.
    Registry.setConfigs({
      synthetic_dbx: { type: "databricks", server_hostname: "dbc-0.cloud.databricks.com", http_path: "/sql/1.0/warehouses/abc123", access_token: "x" },
      synthetic_sf: { type: "snowflake", account: "a", user: "u", password: "p", warehouse: "W" },
    } as any)
  })
  afterEach(() => Registry.reset())

  test("cover every evidence kind of both platforms, field for field", () => {
    const fields = (report: { findings: { evidence: Record<string, unknown> }[] }) =>
      Object.fromEntries(report.findings.map((one) => [one.evidence.kind, Object.keys(one.evidence).sort()]))
    const databricks = fields(databricksFull.report as never)
    const snowflake = fields(snowflakeFull.report as never)
    expect(Object.keys(databricks).sort()).toEqual(Object.keys(DATABRICKS_FIELDS).sort())
    expect(Object.keys(snowflake).sort()).toEqual(Object.keys(SNOWFLAKE_FIELDS).sort())
    for (const [kind, expected] of Object.entries(DATABRICKS_FIELDS)) expect(databricks[kind]).toEqual([...expected].sort())
    for (const [kind, expected] of Object.entries(SNOWFLAKE_FIELDS)) expect(snowflake[kind]).toEqual([...expected].sort())
    // The report-level shape the formatters read.
    expect(Object.keys(databricksFull.report).sort()).toEqual(["findings", "lookback_days", "total", "what_if"])
    expect(Object.keys(snowflakeFull.report).sort()).toEqual(["findings", "lookback_days", "price_per_credit", "total", "what_if"])
    expect(Object.keys(databricksFull.report.what_if[0]).sort()).toEqual(["choices", "current_label", "current_monthly_cost", "resource_id", "resource_name", "workspace_id"])
  })

  test("every Databricks finding reads without holes, a size core leaves out included", () => {
    const result = databricksResult(databricksFull.report)
    for (const finding of result.report!.findings) {
      const lines = Databricks.evidenceLines(finding)
      expect(lines.length).toBeGreaterThan(0)
      for (const line of lines) expectNoHoles(line)
    }
    const text = Databricks.formatSavings(result)
    expectNoHoles(text)
    expect(text).not.toContain(" ? ")
    // The warehouse core reports no size for.
    expect(text).toContain("PRO warehouse, 70% idle")
    // The job whose workspace billed no jobs compute, priced at core's estimated rate.
    expect(text).toContain("(estimated: the workspace billed no jobs compute)")
    expect(text).toContain("Auto-termination off")
    expect(text).toContain("What synthetic idle classic (now SMALL (CLASSIC)")
  })

  test("every Snowflake finding reads without holes; the cluster wording uses the counts core reports", () => {
    for (const source of ["rate_sheet", "list_price"] as const) {
      const result = snowflakeResult(snowflakeFull.report, source)
      for (const finding of result.report!.findings) {
        const lines = Snowflake.evidenceLines(finding)
        expect(lines.length).toBeGreaterThan(0)
        for (const line of lines) expectNoHoles(line)
      }
      expectNoHoles(Snowflake.formatSavings(result))
    }
    const text = Snowflake.formatSavings(snowflakeResult(snowflakeFull.report, "rate_sheet"))
    expect(text).toContain("Its top cluster (3 of 3) was barely needed on 7 days (up to 90% idle)")
    expect(text).toContain("Lowering the maximum from 3 to 2 clusters may add some queueing; no dollar estimate")
  })

  test("reports with no dollar estimate read as such", () => {
    const snowflake = Snowflake.formatSavings(snowflakeResult(snowflakeUnpriced.report, "list_price"))
    expectNoHoles(snowflake)
    expect(snowflake).toContain("list price (no dollar rate could be read from the account's rate sheet)")
    expect(snowflake).toContain("SYNTHETIC_MULTI_WH (warehouse) · Underutilized Cluster · no dollar estimate (low)")
    expect(snowflake).not.toContain("Total:")

    const databricks = Databricks.formatSavings(databricksResult(databricksUnpriced.report))
    expectNoHoles(databricks)
    expect(databricks).toContain("No savings found.")
  })

  test("the tools' own output, as `altimate-code tool run` prints it, has no holes either", async () => {
    const cases = [
      ["finops.databricks_savings", Databricks.FinopsDatabricksSavingsTool, databricksResult(databricksFull.report)],
      ["finops.databricks_savings", Databricks.FinopsDatabricksSavingsTool, databricksResult(databricksUnpriced.report)],
      ["finops.snowflake_savings", Snowflake.FinopsSnowflakeSavingsTool, snowflakeResult(snowflakeFull.report, "rate_sheet")],
      ["finops.snowflake_savings", Snowflake.FinopsSnowflakeSavingsTool, snowflakeResult(snowflakeUnpriced.report, "list_price")],
    ] as const
    for (const [method, definition, result] of cases) {
      Dispatcher.register(method as any, async () => result)
      const tool = await initTool(definition as any)
      const ctx = { sessionID: "test", messageID: "test", agent: "test", abort: new AbortController().signal, metadata: () => {}, ask: async () => {} }
      const out = await tool.execute({}, ctx)
      expectNoHoles(out.title)
      expectNoHoles(out.output)
    }
  })
})
